//! Regenerates the parity test's fixture (`tests/data/`) from real lists and adblock-rust's
//! request corpus (`data/requests.json` in the adblock-rust repository, one JSON object per
//! line: `{"url", "frameUrl", "cpt"}`).
//!
//! cargo run --release --example parity_fixture -- <requests.json> <list.txt>...
//!
//! It keeps every 97th request, and from the lists: every filter that decides one of those
//! requests (the block and the exception), every filter with an option that changes how a
//! decision is made ($redirect, $removeparam, $important, $badfilter, $csp, $generichide), and
//! every 40th other network filter. Run `cargo test` afterwards and update
//! `tests/data/parity.golden` with the hash it reports, after checking the change is expected.

use std::collections::BTreeSet;
use std::ffi::CString;
use std::io::Write;
use std::ptr;

use shields::*;

const REQUEST_STRIDE: usize = 97;
const FILTER_STRIDE: usize = 40;
const DECISIVE_OPTIONS: [&str; 7] = [
    "redirect=",
    "redirect-rule=",
    "removeparam",
    "important",
    "badfilter",
    "csp=",
    "generichide",
];

#[derive(serde::Deserialize)]
struct Explanation {
    rule: Option<Rule>,
    exception: Option<Rule>,
}

#[derive(serde::Deserialize)]
struct Rule {
    text: Option<String>,
}

fn main() {
    let arguments: Vec<String> = std::env::args().collect();
    let [_, corpus, lists @ ..] = arguments.as_slice() else {
        eprintln!("usage: parity_fixture <requests.json> <list.txt>...");
        std::process::exit(64);
    };
    let fixture = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/data");
    std::fs::create_dir_all(&fixture).expect("creates tests/data");

    let texts: Vec<String> = lists
        .iter()
        .map(|path| std::fs::read_to_string(path).expect("reads a list"))
        .collect();
    let set = shields_filter_set_new(true);
    for text in &texts {
        unsafe {
            shields_filter_set_add_list(set, text.as_ptr(), text.len(), 0, 0, ptr::null_mut())
        };
    }
    let engine = unsafe { shields_engine_build(set) };
    assert!(!engine.is_null());

    let corpus = std::fs::read_to_string(corpus).expect("reads the corpus");
    let requests: Vec<&str> = corpus.lines().step_by(REQUEST_STRIDE).collect();
    let mut filters = BTreeSet::new();
    for line in &requests {
        let request: serde_json::Value = serde_json::from_str(line).expect("corpus lines are JSON");
        let field = |name: &str| CString::new(request[name].as_str().unwrap_or_default()).unwrap();
        let (url, frame, kind) = (field("url"), field("frameUrl"), field("cpt"));
        let mut json = ShieldsBuffer {
            data: ptr::null_mut(),
            len: 0,
            capacity: 0,
        };
        let status = unsafe {
            shields_engine_explain(
                engine,
                url.as_ptr(),
                frame.as_ptr(),
                kind.as_ptr(),
                c"GET".as_ptr(),
                &mut json,
            )
        };
        if status == SHIELDS_OK {
            let bytes = unsafe { std::slice::from_raw_parts(json.data, json.len) };
            let explanation: Explanation =
                serde_json::from_slice(bytes).expect("explanations are JSON");
            for rule in [explanation.rule, explanation.exception]
                .into_iter()
                .flatten()
            {
                filters.extend(rule.text);
            }
        }
        unsafe { shields_buffer_free(&mut json) };
    }
    for text in &texts {
        let network = text
            .lines()
            .map(str::trim)
            .filter(|line| !line.is_empty() && !line.starts_with('!') && !line.contains('#'));
        for (index, line) in network.enumerate() {
            if index % FILTER_STRIDE == 0
                || DECISIVE_OPTIONS.iter().any(|option| line.contains(option))
            {
                filters.insert(line.to_string());
            }
        }
    }

    let mut output =
        std::fs::File::create(fixture.join("filters.txt")).expect("creates filters.txt");
    writeln!(
        output,
        "! Parity fixture: a slice of EasyList, EasyPrivacy (GPLv3 or CC BY-SA 3.0, easylist.to) and\n\
         ! uBlock Origin's lists (GPLv3, github.com/uBlockOrigin/uAssets). Generated by\n\
         ! examples/parity_fixture.rs; do not edit by hand."
    )
    .unwrap();
    for filter in &filters {
        writeln!(output, "{filter}").unwrap();
    }
    let mut output =
        std::fs::File::create(fixture.join("requests.jsonl")).expect("creates requests.jsonl");
    for line in &requests {
        writeln!(output, "{line}").unwrap();
    }
    println!("{} filters, {} requests", filters.len(), requests.len());
    unsafe {
        shields_engine_free(engine);
        shields_filter_set_free(set);
    }
}
